# Карта рисуется блоками; выход E — 2×2, стоит на полу (нижняя строка — y).
import json, sys

class G:
    def __init__(s, W, H=18):
        s.W, s.H = W, H
        s.m = [['.'] * W for _ in range(H)]
        for x in range(W): s.m[0][x] = s.m[H-1][x] = '#'
        for y in range(H): s.m[y][0] = s.m[y][W-1] = '#'
    def fill(s, x0, x1, y0, y1, ch='#'):
        for y in range(y0, y1+1):
            for x in range(x0, x1+1): s.m[y][x] = ch
    def put(s, x, y, ch): s.m[y][x] = ch
    def exit(s, x, y): s.fill(x, x+1, y-1, y, 'E')
    def rows(s): return [''.join(r) for r in s.m]

def lvl(g, name, hint, motif, start, enemies=(), pickups=(), decor=(), v=None, **kw):
    m = g.rows()
    d = dict(name=name, motif=motif, hue=None, dark=False, darkA=.94, hint=hint, order='abc', map=m,
             enemies=[dict(t=e[0], tx=e[1], ty=e[2]) for e in enemies],
             pickups=[dict(t=p[0], tx=p[1], ty=p[2]) for p in pickups],
             movers=[], flags=[], tier=0,
             decor=[dict(t=t, tx=x, ty=y, sc=sc, fl=0, fr=0) for (t, x, y, sc) in decor])
    if v: d['v'] = v
    d.update(kw)
    return d

